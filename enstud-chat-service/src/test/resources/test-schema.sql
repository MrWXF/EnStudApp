CREATE TABLE IF NOT EXISTS enstud_chat_session (
    id BIGINT NOT NULL AUTO_INCREMENT, user_id BIGINT NOT NULL,
    title VARCHAR(100) DEFAULT NULL, scenario VARCHAR(50) DEFAULT 'FREE',
    message_count INT DEFAULT 0, is_deleted TINYINT DEFAULT 0,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id)
);
CREATE TABLE IF NOT EXISTS enstud_chat_message (
    id BIGINT NOT NULL AUTO_INCREMENT, session_id BIGINT NOT NULL,
    role VARCHAR(20) NOT NULL, content TEXT NOT NULL,
    grammar_issues TEXT DEFAULT NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id)
);
