CREATE TABLE IF NOT EXISTS enstud_writing (
    id BIGINT NOT NULL AUTO_INCREMENT, user_id BIGINT NOT NULL,
    title VARCHAR(200) NOT NULL, content CLOB NOT NULL,
    word_count INT DEFAULT 0, topic_type VARCHAR(50) DEFAULT NULL,
    score INT DEFAULT NULL, correction TEXT DEFAULT NULL,
    is_deleted TINYINT DEFAULT 0, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, PRIMARY KEY (id)
);
